/*
XGPU_VULKAN_FSR_SHADERS.H

display.temporal_aa "fsr"'s compute passes as SPIR-V: AMD FidelityFX Super
Resolution 3.1's upscaler (port/third_party/fidelityfx-fsr3, MIT),
generated by tools/vulkan_fsr_shaders.py, with each pass's bindings (set 0)
read back from its SPIR-V: the resource each binding is, and whether it is
sampled (a texture), written (a storage image), a uniform block or a
sampler. xgpu_vulkan_fsr.c dispatches them.
*/

#ifndef XGPU_VULKAN_FSR_SHADERS_H
#define XGPU_VULKAN_FSR_SHADERS_H

#include <stdint.h>
#include <stddef.h>

/* the passes, in the order a frame dispatches them, the reactive mask's
(the transparent draws found from the view before them) apart */
enum xgpu_vulkan_fsr_pass
{
	XGPU_VULKAN_FSR_PASS_PREPARE_INPUTS,
	XGPU_VULKAN_FSR_PASS_LUMA_PYRAMID,
	XGPU_VULKAN_FSR_PASS_SHADING_CHANGE_PYRAMID,
	XGPU_VULKAN_FSR_PASS_SHADING_CHANGE,
	XGPU_VULKAN_FSR_PASS_PREPARE_REACTIVITY,
	XGPU_VULKAN_FSR_PASS_LUMA_INSTABILITY,
	XGPU_VULKAN_FSR_PASS_ACCUMULATE,
	XGPU_VULKAN_FSR_PASS_AUTOGEN_REACTIVE,
	XGPU_VULKAN_FSR_PASS_COUNT
};

/* a binding's kind */
enum
{
	XGPU_VULKAN_FSR_TEXTURE,
	XGPU_VULKAN_FSR_IMAGE,
	XGPU_VULKAN_FSR_BUFFER,
	XGPU_VULKAN_FSR_SAMPLER,
};

/* the resources (the SDK's FFX_FSR3UPSCALER_RESOURCE_IDENTIFIER_*'s): a
texture and an image of the same name are one resource, except those kept
two frames (the accumulation, the luma history, the upscaled colour), which
are read from the frame before's and written to this frame's */
enum xgpu_vulkan_fsr_resource
{
	XGPU_VULKAN_FSR_INPUT_COLOR,
	XGPU_VULKAN_FSR_INPUT_OPAQUE_ONLY,
	XGPU_VULKAN_FSR_INPUT_MOTION_VECTORS,
	XGPU_VULKAN_FSR_INPUT_DEPTH,
	XGPU_VULKAN_FSR_INPUT_EXPOSURE,
	XGPU_VULKAN_FSR_FRAME_INFO,
	XGPU_VULKAN_FSR_REACTIVE_MASK,
	XGPU_VULKAN_FSR_TRANSPARENCY_AND_COMPOSITION_MASK,
	XGPU_VULKAN_FSR_RECONSTRUCTED_PREVIOUS_NEAREST_DEPTH,
	XGPU_VULKAN_FSR_DILATED_MOTION_VECTORS,
	XGPU_VULKAN_FSR_DILATED_DEPTH,
	XGPU_VULKAN_FSR_INTERNAL_UPSCALED,
	XGPU_VULKAN_FSR_ACCUMULATION,
	XGPU_VULKAN_FSR_LUMA_HISTORY,
	XGPU_VULKAN_FSR_LANCZOS_LUT,
	XGPU_VULKAN_FSR_SPD_MIPS,
	XGPU_VULKAN_FSR_SPD_MIP0,
	XGPU_VULKAN_FSR_SPD_MIP1,
	XGPU_VULKAN_FSR_SPD_MIP2,
	XGPU_VULKAN_FSR_SPD_MIP3,
	XGPU_VULKAN_FSR_SPD_MIP4,
	XGPU_VULKAN_FSR_SPD_MIP5,
	XGPU_VULKAN_FSR_SPD_ATOMIC,
	XGPU_VULKAN_FSR_DILATED_REACTIVE_MASKS,
	XGPU_VULKAN_FSR_NEW_LOCKS,
	XGPU_VULKAN_FSR_FARTHEST_DEPTH,
	XGPU_VULKAN_FSR_FARTHEST_DEPTH_MIP1,
	XGPU_VULKAN_FSR_SHADING_CHANGE,
	XGPU_VULKAN_FSR_CURRENT_LUMA,
	XGPU_VULKAN_FSR_PREVIOUS_LUMA,
	XGPU_VULKAN_FSR_LUMA_INSTABILITY,
	XGPU_VULKAN_FSR_UPSCALED_OUTPUT,
	XGPU_VULKAN_FSR_AUTOREACTIVE,
	XGPU_VULKAN_FSR_AUTOCOMPOSITION,
	XGPU_VULKAN_FSR_CONSTANTS,
	XGPU_VULKAN_FSR_SPD_CONSTANTS,
	XGPU_VULKAN_FSR_REACTIVE_CONSTANTS,
	XGPU_VULKAN_FSR_POINT_SAMPLER,
	XGPU_VULKAN_FSR_LINEAR_SAMPLER,
	XGPU_VULKAN_FSR_RESOURCE_COUNT
};

struct xgpu_vulkan_fsr_binding
{
	uint16_t binding;
	uint8_t kind, resource;
};

struct xgpu_vulkan_fsr_program
{
	const uint32_t *words;
	size_t count;
	const struct xgpu_vulkan_fsr_binding *bindings;
	size_t binding_count;
};

/* [0] an SDR colour input's, [1] an HDR one's (linear, display.hdr's) */
extern const struct xgpu_vulkan_fsr_program xgpu_vulkan_fsr_programs[2][XGPU_VULKAN_FSR_PASS_COUNT];

#endif
