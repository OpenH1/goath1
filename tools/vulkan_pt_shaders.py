#!/usr/bin/env python3
"""Build the path tracing's fixed compute kernels for Vulkan
(docs/rt-plan/4-path-tracing.md, "Shaders").

Run with glslangValidator and spirv-val on PATH:
    python3 tools/vulkan_pt_shaders.py
Each port/linux/vulkan/pt/<name>.comp is compiled to SPIR-V (Vulkan 1.2) and
embedded in port/linux/vulkan/xgpu_vulkan_pt_shaders.c as
xgpu_vulkan_pt_<name>_words and _count, so the game needs no shader compiler.
--check verifies that the checked-in file still matches its sources.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import struct
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ROOT / "port/linux/vulkan/pt"
OUTPUT = ROOT / "port/linux/vulkan/xgpu_vulkan_pt_shaders.c"


def compile_words(source: Path) -> list[int]:
    with tempfile.TemporaryDirectory() as folder:
        spirv = Path(folder) / "out.spv"
        subprocess.run(["glslangValidator", "--target-env", "vulkan1.2", "-V", str(source), "-o", str(spirv)],
                       check=True, stdout=subprocess.DEVNULL)
        subprocess.run(["spirv-val", "--target-env", "vulkan1.2", str(spirv)], check=True)
        data = spirv.read_bytes()
    return list(struct.unpack(f"<{len(data) // 4}I", data))


def generate() -> str:
    text = ["/* generated by tools/vulkan_pt_shaders.py from port/linux/vulkan/pt: do not edit */\n",
            "#include <stdint.h>\n"]
    for source in sorted(SOURCES.glob("*.comp")):
        name = source.stem
        words = compile_words(source)
        text.append(f"\nconst uint32_t xgpu_vulkan_pt_{name}_words[] =\n{{")
        for at in range(0, len(words), 8):
            text.append("\n\t" + ", ".join(f"0x{word:08x}u" for word in words[at:at + 8]) + ",")
        text.append("\n};\n")
        text.append(f"const uint32_t xgpu_vulkan_pt_{name}_count = {len(words)}u;\n")
    return "".join(text)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    text = generate()
    if arguments.check:
        if OUTPUT.read_text() != text:
            print(f"{OUTPUT} is out of date: run tools/vulkan_pt_shaders.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
